export function getLocalizedBusinessType(bizType, lang = 'en') {
  if (!bizType) return '';
  const trimmed = String(bizType).trim();
  if (lang === 'mr' || lang === 'hi') {
    if (BUSINESS_TYPE_TRANSLATIONS[trimmed] && BUSINESS_TYPE_TRANSLATIONS[trimmed][lang]) {
      return BUSINESS_TYPE_TRANSLATIONS[trimmed][lang];
    }
    // Partial match for composites like "Dairy Farming (5+ cattle)"
    for (const [key, val] of Object.entries(BUSINESS_TYPE_TRANSLATIONS)) {
      if (trimmed.toLowerCase().includes(key.toLowerCase()) && val[lang]) {
        return val[lang];
      }
    }
  }
  return trimmed;
}

export function getLocalizedCapacity(cap, lang = 'en') {
  if (!cap) return '';
  let str = '';
  if (typeof cap === 'object' && cap.amount !== undefined) {
    str = `${cap.amount} ${cap.unit || ''}`.trim();
  } else {
    str = String(cap);
  }

  if (lang === 'mr') {
    return str
      .replace(/animals\/hour/gi, 'जनावरे / तास')
      .replace(/kg\/hour/gi, 'किलो / तास')
      .replace(/Liters\/batch/gi, 'लिटर / बॅच')
      .replace(/liters\/batch/gi, 'लिटर / बॅच')
      .replace(/samples\/hour/gi, 'नमुने / तास')
      .replace(/bottles\/min/gi, 'बाटल्या / मिनिट')
      .replace(/kg\/batch/gi, 'किलो / बॅच')
      .replace(/Single Phase/gi, 'सिंगल फेज')
      .replace(/3-Phase|Three Phase/gi, '३-फेज');
  } else if (lang === 'hi') {
    return str
      .replace(/animals\/hour/gi, 'पशु / घंटा')
      .replace(/kg\/hour/gi, 'किग्रा / घंटा')
      .replace(/Liters\/batch/gi, 'लीटर / बैच')
      .replace(/liters\/batch/gi, 'लीटर / बैच')
      .replace(/samples\/hour/gi, 'सैंपल / घंटा')
      .replace(/bottles\/min/gi, 'बोतल / मिनट')
      .replace(/kg\/batch/gi, 'किग्रा / बैच')
      .replace(/Single Phase/gi, 'सिंगल फेज')
      .replace(/3-Phase|Three Phase/gi, '3-फेज');
  }
  return str;
}

